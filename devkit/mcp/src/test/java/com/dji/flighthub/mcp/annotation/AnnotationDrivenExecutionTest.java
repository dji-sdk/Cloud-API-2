package com.dji.flighthub.mcp.annotation;

import com.dji.flighthub.mcp.security.SecurityLevel;
import com.dji.flighthub.mcp.session.SessionContext;
import com.dji.flighthub.mcp.session.SessionManager;
import com.dji.flighthub.mcp.tools.AbstractMcpTool;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.HashMap;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * 注解驱动执行模式集成测试：验证 @McpTool + @McpParam 注解驱动的 Tool
 * 能自动生成 definition、执行参数校验、管理 ToolContext 生命周期。
 *
 * @author DJI FlightHub SDK Team
 */
@SuppressWarnings("unchecked")
class AnnotationDrivenExecutionTest {

    private SessionManager mockSessionManager;
    private SessionContext mockSession;

    @BeforeEach
    void setUp() {
        mockSessionManager = mock(SessionManager.class);
        mockSession = new SessionContext("s1", "ws-uuid", "test-ws", 3);
        when(mockSessionManager.getActiveSession()).thenReturn(mockSession);
        when(mockSessionManager.getOrAutoConnect()).thenReturn(mockSession);
    }

    @AfterEach
    void cleanup() {
        ToolContext.clear();
    }

    // ==================== 测试用注解驱动 Tool ====================

    /**
     * 只读 Tool：仅需 session，无 confirm，安全等级 L0。
     */
    @McpTool(name = "test_read", description = "Read-only test tool")
    static class ReadOnlyTool extends AbstractMcpTool {

        @McpParam(description = "Target device serial number", required = true)
        private String device_sn;

        ReadOnlyTool(SessionManager sm) {
            super(sm);
        }

        @Override
        protected Map<String, Object> doExecute(ToolContext ctx) {
            return successResult(
                    Map.of("device", ctx.getString("device_sn")),
                    "Got device info");
        }
    }

    /**
     * 需要确认的 L1 Tool：需要 session + 安全等级 + confirm。
     */
    @McpTool(
            name = "test_control",
            description = "Control test tool",
            securityLevel = SecurityLevel.REVERSIBLE,
            prerequisites = {Prerequisite.SESSION, Prerequisite.SECURITY_LEVEL},
            requiresConfirm = true,
            targetSnParam = "drone_sn"
    )
    static class ControlTool extends AbstractMcpTool {

        @McpParam(description = "Target drone SN", required = true)
        private String drone_sn;

        @McpParam(description = "Action to perform", required = true,
                enumValues = {"start", "stop"})
        private String action;

        ControlTool(SessionManager sm) {
            super(sm);
        }

        @Override
        protected Map<String, Object> doExecute(ToolContext ctx) {
            return successResult(
                    Map.of("drone", ctx.getString("drone_sn"),
                            "action", ctx.getString("action")),
                    "Control command sent");
        }
    }

    // ==================== getToolDefinition 测试 ====================

    @Test
    void annotatedTool_shouldAutoGenerateDefinition() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);
        Map<String, Object> def = tool.getToolDefinition();

        assertEquals("test_read", def.get("name"));
        assertEquals("Read-only test tool", def.get("description"));

        Map<String, Object> schema = (Map<String, Object>) def.get("inputSchema");
        assertNotNull(schema);
        assertEquals("object", schema.get("type"));

        Map<String, Object> props = (Map<String, Object>) schema.get("properties");
        assertTrue(props.containsKey("device_sn"), "应包含 device_sn 属性");
        assertTrue(props.containsKey("dry_run"), "应自动追加 dry_run 属性");
    }

    @Test
    void annotatedTool_shouldIncludeRequiredArray() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);
        Map<String, Object> def = tool.getToolDefinition();
        Map<String, Object> schema = (Map<String, Object>) def.get("inputSchema");

        var required = (java.util.List<String>) schema.get("required");
        assertNotNull(required);
        assertTrue(required.contains("device_sn"));
    }

    // ==================== execute 正常路径 ====================

    @Test
    void annotatedTool_shouldExecuteSuccessfully() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);
        Map<String, Object> args = new HashMap<>();
        args.put("device_sn", "DRONE-001");

        Map<String, Object> result = tool.execute(args);

        assertEquals(true, result.get("success"));
        Map<String, Object> data = (Map<String, Object>) result.get("data");
        assertEquals("DRONE-001", data.get("device"));
    }

    // ==================== 前置条件校验 ====================

    @Test
    void annotatedTool_shouldReturnError_whenNoSession() {
        when(mockSessionManager.getActiveSession()).thenReturn(null);
        when(mockSessionManager.getOrAutoConnect()).thenReturn(null);
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);

        Map<String, Object> args = new HashMap<>();
        args.put("device_sn", "X");

        Map<String, Object> result = tool.execute(args);

        assertEquals(false, result.get("success"));
        assertTrue(result.get("error_message").toString().toLowerCase().contains("session")
                        || result.get("suggestion").toString().toLowerCase().contains("connect"),
                "错误信息应提示缺少 session");
    }

    // ==================== 参数校验 ====================

    @Test
    void annotatedTool_shouldReturnError_whenRequiredParamMissing() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);

        Map<String, Object> result = tool.execute(new HashMap<>());

        assertEquals(false, result.get("success"));
        assertTrue(result.get("error_message").toString().contains("device_sn"),
                "错误信息应指明缺少的参数名");
    }

    // ==================== dry_run 支持 ====================

    @Test
    void annotatedTool_shouldSupportDryRun() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);
        Map<String, Object> args = new HashMap<>();
        args.put("device_sn", "DRONE-001");
        args.put("dry_run", true);

        Map<String, Object> result = tool.execute(args);

        assertEquals(true, result.get("success"));
        assertEquals(true, result.get("_dry_run"));
        assertTrue(result.get("message").toString().contains("test_read"));
    }

    // ==================== ToolContext 生命周期 ====================

    @Test
    void annotatedTool_shouldCleanupToolContext_afterExecution() {
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);
        Map<String, Object> args = new HashMap<>();
        args.put("device_sn", "DRONE-001");

        tool.execute(args);

        assertNull(ToolContext.current(),
                "ToolContext should be cleaned up after execution (ThreadLocal cleared)");
    }

    @Test
    void annotatedTool_shouldCleanupToolContext_evenOnError() {
        when(mockSessionManager.getActiveSession()).thenReturn(null);
        when(mockSessionManager.getOrAutoConnect()).thenReturn(null);
        ReadOnlyTool tool = new ReadOnlyTool(mockSessionManager);

        tool.execute(new HashMap<>());

        assertNull(ToolContext.current(),
                "ToolContext should be cleaned up even when execution fails");
    }

    // ==================== requiresHumanConfirmation / getSecurityLevel ====================

    @Test
    void annotatedTool_requiresHumanConfirmation_shouldReflectAnnotation() {
        ReadOnlyTool readTool = new ReadOnlyTool(mockSessionManager);
        assertFalse(readTool.requiresHumanConfirmation(),
                "ReadOnlyTool 不需要 confirm");

        ControlTool controlTool = new ControlTool(mockSessionManager);
        assertTrue(controlTool.requiresHumanConfirmation(),
                "ControlTool 需要 confirm");
    }

    @Test
    void annotatedTool_getSecurityLevel_shouldReflectAnnotation() {
        ReadOnlyTool readTool = new ReadOnlyTool(mockSessionManager);
        assertEquals(SecurityLevel.READ_ONLY, readTool.getSecurityLevel());

        ControlTool controlTool = new ControlTool(mockSessionManager);
        assertEquals(SecurityLevel.REVERSIBLE, controlTool.getSecurityLevel());
    }

    // ==================== confirm 校验 ====================

    @Test
    void controlTool_shouldRequireConfirm() {
        ControlTool tool = new ControlTool(mockSessionManager);
        Map<String, Object> args = new HashMap<>();
        args.put("drone_sn", "DRONE-001");
        args.put("action", "start");
        // 不传 confirm=true

        Map<String, Object> result = tool.execute(args);

        assertEquals(false, result.get("success"));
        assertTrue(result.get("error_message").toString().toLowerCase().contains("confirm")
                        || result.get("suggestion").toString().toLowerCase().contains("confirm"),
                "应提示需要确认");
    }

    @Test
    void controlTool_shouldExecute_whenConfirmed() {
        ControlTool tool = new ControlTool(mockSessionManager);
        Map<String, Object> args = new HashMap<>();
        args.put("drone_sn", "DRONE-001");
        args.put("action", "start");
        args.put("confirm", true);

        Map<String, Object> result = tool.execute(args);

        assertEquals(true, result.get("success"));
        Map<String, Object> data = (Map<String, Object>) result.get("data");
        assertEquals("DRONE-001", data.get("drone"));
        assertEquals("start", data.get("action"));
    }
}
